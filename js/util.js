// localStorage bisa melempar error (mode privat, storage penuh), jadi selalu dibungkus.
const Store = {
  get(key, fallback) {
    try {
      const raw = localStorage.getItem('st:' + key);
      return raw == null ? fallback : JSON.parse(raw);
    } catch {
      return fallback;
    }
  },
  set(key, value) {
    try { localStorage.setItem('st:' + key, JSON.stringify(value)); } catch { /* abaikan */ }
  },
  remove(key) {
    try { localStorage.removeItem('st:' + key); } catch { /* abaikan */ }
  },
};

// IndexedDB untuk file besar (background yang di-upload), karena localStorage cuma ~5MB.
const DB = (() => {
  let dbPromise = null;
  function open() {
    if (!dbPromise) {
      dbPromise = new Promise((resolve, reject) => {
        const req = indexedDB.open('study-timer', 1);
        req.onupgradeneeded = () => req.result.createObjectStore('files');
        req.onsuccess = () => resolve(req.result);
        req.onerror = () => reject(req.error);
      });
    }
    return dbPromise;
  }
  async function put(key, value) {
    const db = await open();
    return new Promise((resolve, reject) => {
      const tx = db.transaction('files', 'readwrite');
      tx.objectStore('files').put(value, key);
      tx.oncomplete = () => resolve();
      tx.onerror = () => reject(tx.error);
    });
  }
  async function get(key) {
    const db = await open();
    return new Promise((resolve, reject) => {
      const req = db.transaction('files').objectStore('files').get(key);
      req.onsuccess = () => resolve(req.result);
      req.onerror = () => reject(req.error);
    });
  }
  return { put, get };
})();

let toastTimer = null;
function toast(message, ms = 2600) {
  const el = $('#toast');
  el.textContent = message;
  el.classList.add('show');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => el.classList.remove('show'), ms);
}

