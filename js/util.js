function mountIcons(root = document) {
  $$('i[data-icon]', root).forEach((el) => {
    el.outerHTML = icon(el.dataset.icon).replace('<svg ', el.id ? `<svg id="${el.id}" ` : '<svg ');
  });
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
